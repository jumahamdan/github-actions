#!/usr/bin/env python3
"""Expand named workflow fragments into the ordinary YAML consumed by GitHub.

Sources live in workflow-templates/workflows/. Fragments live in the YAML files
directly under workflow-templates/. A {$ref: namespace.name} node expands one
fragment; {$merge: [mapping, ...]} combines disjoint mappings. Neither directive
executes code, substitutes strings, overrides a key, or reads a referenced path.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
NAME = re.compile(r"[a-z][a-z0-9_-]*")
WORKFLOW = re.compile(r"v2-[a-z0-9-]+\.yml")
HEADER = "# Generated by scripts/generate-workflows.py; edit workflow-templates/ instead.\n"


class GenerationError(ValueError):
    """An ambiguous, unsafe or incomplete workflow source."""


class StrictLoader(yaml.SafeLoader):
    def compose_node(self, parent, index):
        if self.check_event(yaml.AliasEvent):
            raise GenerationError("YAML aliases are not supported; use a named $ref")
        return super().compose_node(parent, index)


# GitHub uses YAML 1.2 booleans. In particular an ordinary `on:` event key must
# stay a string instead of becoming PyYAML's YAML 1.1 boolean True.
StrictLoader.yaml_implicit_resolvers = {
    key: [(tag, pattern) for tag, pattern in values if tag != "tag:yaml.org,2002:bool"]
    for key, values in yaml.SafeLoader.yaml_implicit_resolvers.items()
}
StrictLoader.add_implicit_resolver("tag:yaml.org,2002:bool", re.compile(r"^(?:true|false)$", re.I), list("tTfF"))


def _mapping(loader, node):
    result = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node)
        if not isinstance(key, str) or key == "<<":
            raise GenerationError("Source mapping keys must be strings; use $merge for composition")
        if key in result:
            raise GenerationError(f"Duplicate source key: {key}")
        result[key] = loader.construct_object(value_node)
    return result


StrictLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _mapping)


def load_yaml(path):
    """Load an explicit source file without aliases, implicit merges or duplicate keys."""
    try:
        return yaml.load(Path(path).read_text(), Loader=StrictLoader)
    except (OSError, yaml.YAMLError) as exc:
        raise GenerationError(f"Cannot load {path}: {exc}") from exc


def load_fragments(directory):
    """Read namespace.name fragments from immediate *.yml files in a directory."""
    fragments = {}
    for path in sorted(Path(directory).glob("*.yml")):
        if not NAME.fullmatch(path.stem):
            raise GenerationError(f"Invalid fragment namespace: {path.name}")
        data = load_yaml(path)
        if not isinstance(data, dict):
            raise GenerationError(f"Fragment file must be a mapping: {path}")
        for name, value in data.items():
            if not NAME.fullmatch(name):
                raise GenerationError(f"Invalid fragment name: {name}")
            fragments[f"{path.stem}.{name}"] = value
    return fragments


def expand(node, fragments, stack=()):
    """Recursively expand explicit references and disjoint mapping composition."""
    if isinstance(node, list):
        return [expand(value, fragments, stack) for value in node]
    if not isinstance(node, dict):
        return node
    if any(not isinstance(key, str) for key in node):
        raise GenerationError("Source mapping keys must be strings")
    directives = [key for key in node if key.startswith("$")]
    if not directives:
        return {key: expand(value, fragments, stack) for key, value in node.items()}
    if len(node) != 1:
        raise GenerationError("A template directive must be the only key in its mapping")
    if directives == ["$ref"]:
        name = node["$ref"]
        if not isinstance(name, str) or name not in fragments:
            raise GenerationError(f"Unknown fragment reference: {name}")
        if name in stack:
            raise GenerationError("Recursive fragment reference: " + " -> ".join((*stack, name)))
        return expand(fragments[name], fragments, (*stack, name))
    if directives == ["$merge"]:
        parts = node["$merge"]
        if not isinstance(parts, list) or not parts:
            raise GenerationError("$merge requires a nonempty list of mappings")
        result = {}
        for part in parts:
            value = expand(part, fragments, stack)
            if not isinstance(value, dict):
                raise GenerationError("$merge can only combine mappings")
            collisions = result.keys() & value.keys()
            if collisions:
                raise GenerationError("Duplicate merged keys: " + ", ".join(sorted(collisions)))
            result.update(value)
        return result
    raise GenerationError("Unknown template directive: " + ", ".join(directives))


def render_workflows(root=ROOT):
    root = Path(root)
    directory = root / "workflow-templates"
    fragments = load_fragments(directory)
    # Validate unused fragments too, so an invalid shared edit cannot hide until
    # a later workflow starts referring to it.
    for name in fragments:
        expand({"$ref": name}, fragments)
    sources = sorted((directory / "workflows").glob("*.yml"))
    if not sources:
        raise GenerationError("No workflow sources found")
    rendered = {}
    display_names = set()
    for path in sources:
        if not WORKFLOW.fullmatch(path.name):
            raise GenerationError(f"Invalid generated workflow filename: {path.name}")
        data = expand(load_yaml(path), fragments)
        if (not isinstance(data, dict) or not isinstance(data.get("name"), str)
                or not isinstance(data.get("jobs"), dict) or not data["jobs"]
                or not isinstance(data.get("on"), dict) or set(data["on"]) != {"workflow_call"}):
            raise GenerationError(f"Expected a named callable workflow with jobs: {path.name}")
        if data["name"] in display_names:
            raise GenerationError(f"Duplicate workflow display name: {data['name']}")
        display_names.add(data["name"])
        rendered[path.name] = HEADER + yaml.safe_dump(data, sort_keys=False, width=110, allow_unicode=True)
    return rendered


def generate(root=ROOT, *, check=False):
    root = Path(root)
    rendered = render_workflows(root)
    destination = root / ".github/workflows"
    unexpected = {p.name for p in destination.glob("v2-*.yml")} - set(rendered)
    if unexpected:
        raise GenerationError("Generated workflows lack sources: " + ", ".join(sorted(unexpected)))
    changed = [name for name, content in rendered.items()
               if not (destination / name).is_file() or (destination / name).read_text() != content]
    if check and changed:
        raise GenerationError("Stale generated workflows: " + ", ".join(changed))
    if not check:
        destination.mkdir(parents=True, exist_ok=True)
        for name in changed:
            (destination / name).write_text(rendered[name])
    return len(rendered), len(changed)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated YAML differs from its source")
    args = parser.parse_args()
    try:
        count, changed = generate(check=args.check)
    except GenerationError as exc:
        print(f"Workflow generation: {exc}", file=sys.stderr)
        return 1
    print(f"Workflow generation: {count} workflows, {changed} changed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
